"""Classical path generators: stationary block bootstrap and filtered historical simulation (FHS)."""
from __future__ import annotations

import numpy as np
import pandas as pd


def block_bootstrap_paths(returns: pd.DataFrame, n_paths: int, horizon: int, block: int = 21, seed: int = 0) -> np.ndarray:
    """Stationary bootstrap (Politis-Romano) of the joint daily return vectors: (n_paths, horizon, C)."""
    a = returns.dropna().to_numpy(float)
    T = len(a)
    rng = np.random.default_rng(seed)
    out = np.empty((n_paths, horizon, a.shape[1]))
    for p in range(n_paths):
        i = 0
        while i < horizon:
            s = rng.integers(0, T)
            L = min(rng.geometric(1 / block), horizon - i)
            out[p, i:i + L] = a[(s + np.arange(L)) % T]
            i += L
    return out


def fhs_paths(returns: pd.DataFrame, n_paths: int, horizon: int, seed: int = 0, max_persistence: float = 0.99) -> np.ndarray:
    """Filtered historical simulation (Barone-Adesi, Giannopoulos and Vosper, 1999).

    Each channel gets a GJR-GARCH(1,1) with Student-t errors; the standardised residual VECTORS are resampled jointly
    (keeping their cross-sectional dependence, including tail co-movement) and re-filtered through each channel's
    variance recursion, with variance targeting (long-run variance = sample variance), persistence capped at
    `max_persistence`, and the recursion started at the long-run variance. Volatility clustering is regenerated by the model;
    the shock dependence is empirical."""
    from arch import arch_model

    from fmflow.risk.garch import fit_quietly
    a = returns.dropna()
    fits, resid = [], []
    for c in a.columns:
        f = fit_quietly(arch_model(a[c] * 100, mean="Constant", vol="GARCH", p=1, o=1, q=1, dist="t"))
        fits.append(f)
        # residuals around the SAMPLE mean: the t-likelihood location is a robust centre, not the mean, and using it
        # would inject a spurious drift of (mean - location) per day into every simulated path
        resid.append((a[c] * 100 - a[c].mean() * 100) / f.conditional_volatility)
    Z = pd.concat(resid, axis=1).dropna().to_numpy(float)
    Z = Z - Z.mean(0)                                                 # zero-mean shocks: drift comes only from the sample mean
    rng = np.random.default_rng(seed)
    pick = rng.integers(0, len(Z), size=(n_paths, horizon))          # one joint residual draw shared by all channels
    out = np.empty((n_paths, horizon, a.shape[1]))
    for j, f in enumerate(fits):
        p = f.params
        mu, al, ga, be = a.iloc[:, j].mean() * 100, p["alpha[1]"], p["gamma[1]"], p["beta[1]"]
        pers = al + ga / 2 + be
        if pers > max_persistence:                                    # shrink a near-integrated fit towards stationarity
            al, ga, be = (x * max_persistence / pers for x in (al, ga, be))
            pers = max_persistence
        var = float((a.iloc[:, j] * 100).var())
        om = (1 - pers) * var                                         # variance targeting (Engle and Mezrich, 1996)
        s2 = np.full(n_paths, var)                                    # start at the long-run (sample) variance
        for t in range(horizon):
            e = np.sqrt(s2) * Z[pick[:, t], j]
            out[:, t, j] = (mu + e) / 100
            s2 = om + (al + ga * (e < 0)) * e ** 2 + be * s2
    return out
